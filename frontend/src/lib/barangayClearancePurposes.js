const UTILITY_SUB_RAW = ["TRANSFER OF METER", "SOLAR NET METERING"];

function dedupePreserveOrder(list) {
  const seen = new Set();
  const out = [];
  for (const item of list) {
    const text = String(item).trim();
    const key = text.toUpperCase();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(text);
  }
  return out;
}

