export function getPortalStrings(lang = DEFAULT_PORTAL_LANG) {
  const base = STRINGS.en;
  const active = STRINGS[lang] || STRINGS.tl;
  return { ...base, ...active };
}

export function getPortalFormDefinitions(shortName, lang = DEFAULT_PORTAL_LANG) {
  const catalog = PORTAL_FORMS[lang] || PORTAL_FORMS.tl;
  const fill = (s) => (s || "").replace(/\{shortName\}/g, shortName || "Barangay");
  return FORM_ORDER.map((id) => {
    const item = catalog[id];
    return {
      id,
      title: item.title,
      description: fill(item.description),
      features: item.features,
    };
  });
}

